#!/usr/bin/env python3
"""Generates src/data/swordFrames.ts from `_ref_repo/Data/Animations/Objects/sword.ani`.

Each frame: duration ms, source rect on link0.png, draw offset relative to (x - 7, y - 16) of Link's
feet anchor (ObjLink draws AnimatorWeapons at EntityPosition - (7, 16)), collision rect relative to the
drawn sprite, and mirror flags. Usage: python scripts/export_sword_frames.py
"""
import json

SRC = '_ref_repo/Data/Animations/Objects/sword.ani'
OUT = 'src/data/swordFrames.ts'
WANTED = ('attack_', 'swing_', 'stand_')

anims = {}
with open(SRC, encoding='utf-8') as f:
    lines = f.read().splitlines()
for line in lines[2:]:
    p = line.split(';')
    if len(p) < 16 or not p[0].startswith(WANTED):
        continue
    n = int(p[5])
    pos = 6
    frames = []
    for _ in range(n):
        t, x, y, w, h, ox, oy, cx, cy, cw, ch, mv, mh = p[pos:pos + 13]
        pos += 13
        frames.append({
            'ms': int(t), 'sx': int(x), 'sy': int(y), 'w': int(w), 'h': int(h),
            'ox': int(ox), 'oy': int(oy),
            'hit': [int(cx), int(cy), int(cw), int(ch)],
            'flipV': mv == 'True', 'flipH': mh == 'True',
        })
    anims[p[0]] = frames

body = json.dumps(anims, indent=2)
out = f"""// AUTO-GENERATED by scripts/export_sword_frames.py from {SRC} — do not edit by hand.
export interface SwordFrame {{
  ms: number;
  sx: number;
  sy: number;
  w: number;
  h: number;
  ox: number; // draw offset from (feetX - 7, feetY - 16)
  oy: number;
  hit: [number, number, number, number]; // collision rect relative to the drawn sprite (w = 0: no hit)
  flipV: boolean;
  flipH: boolean;
}}

export const SWORD_FRAMES: Record<string, SwordFrame[]> = {body};
"""
with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write(out)
print(f'[OK] {OUT}: {len(anims)} animations')
