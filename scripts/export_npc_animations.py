#!/usr/bin/env python3
"""
Converts the NPC animators of `_ref_repo/Data/Animations/NPCs/*.ani` used by the ported NPCs into
`src/data/npcAnimations.ts` (sprite sheet `/assets/ui/npcs.png`).

  python scripts/export_npc_animations.py

.ani format (AnimatorSaveLoad.cs): version, sprite sheet, then one line per animation:
  id;next;loopCount;offsetX;offsetY;frameCount;{time;srcX;srcY;srcW;srcH;offX;offY;colX;colY;colW;colH;mirrorV;mirrorH}*
Each exported frame keeps the draw offset (animation offset + frame offset) relative to the sprite
origin, and `bounds` reproduces Animator.UpdateAnimationSize for the first animation (ObjPerson
centres its sprite with it).
"""

import os

ANI_DIR = os.path.join('_ref_repo', 'Data', 'Animations', 'NPCs')
OUT = os.path.join('src', 'data', 'npcAnimations.ts')

# Animators used by src/data/npcs.ts
ANIMATORS = ['npc04', 'npc07', 'npc09', 'npc_green_boy', 'shopkeeper', 'npc_trendy', 'npc_woman_broom',
             'npc_fisherman', 'dog', 'bowWowSmall', 'BowWow', 'npc_boy_left', 'npc_boy_right']


def parse_ani(path):
    with open(path, encoding='utf-8-sig') as f:
        lines = [l.rstrip('\r\n') for l in f]
    if len(lines) < 2 or lines[1].strip() != 'npcs.png':
        raise SystemExit(f'{path}: expected the npcs.png sheet')
    anims = []
    for line in lines[2:]:
        p = line.split(';')
        if len(p) < 16:
            continue
        anim_id, nxt, loops, aox, aoy, count = p[0].lower(), p[1].lower(), int(p[2]), int(p[3]), int(p[4]), int(p[5])
        frames = []
        for i in range(count):
            f = p[6 + i * 13: 6 + (i + 1) * 13]
            ms, x, y, w, h, ox, oy = (int(v) for v in f[:7])
            frames.append({'ms': ms, 'x': x, 'y': y, 'w': w, 'h': h, 'ox': ox, 'oy': oy,
                           'dx': aox + ox, 'dy': aoy + oy, 'flip': f[12] == 'True'})
        anims.append({'id': anim_id, 'next': nxt, 'loop': loops < 0, 'frames': frames})
    return anims


def bounds(anim):
    # Animator.UpdateAnimationSize: left/top/right/bottom start at 0 and grow with each frame
    left = min([0] + [f['ox'] for f in anim['frames']])
    top = min([0] + [f['oy'] for f in anim['frames']])
    right = max([0] + [f['ox'] + f['w'] for f in anim['frames']])
    bottom = max([0] + [f['oy'] + f['h'] for f in anim['frames']])
    return right - left, bottom - top


def main():
    out = [
        '// AUTO-GENERATED by scripts/export_npc_animations.py from _ref_repo/Data/Animations/NPCs — do not edit by hand.',
        '// Generated data: exceeds the ~300 line guideline on purpose (one frame per line).',
        '',
        'export interface NpcFrame {',
        '  ms: number;',
        '  x: number; // source rectangle on /assets/ui/npcs.png',
        '  y: number;',
        '  w: number;',
        '  h: number;',
        '  dx: number; // draw offset from the sprite origin (animation offset + frame offset)',
        '  dy: number;',
        '  flip: boolean; // mirrored horizontally',
        '}',
        '',
        'export interface NpcAnimation {',
        '  next: string; // played when a non-looping animation ends ("" = hold the last frame)',
        '  loop: boolean;',
        '  frames: NpcFrame[];',
        '}',
        '',
        'export interface NpcAnimator {',
        '  first: string; // Animator default animation (index 0)',
        '  bounds: { w: number; h: number }; // size of the first animation (ObjPerson sprite centring)',
        '  anims: Record<string, NpcAnimation>;',
        '}',
        '',
        'export const NPC_ANIMATORS: Record<string, NpcAnimator> = {',
    ]
    for name in ANIMATORS:
        anims = parse_ani(os.path.join(ANI_DIR, f'{name}.ani'))
        w, h = bounds(anims[0])
        out.append(f'  {name}: {{')
        out.append(f"    first: '{anims[0]['id']}',")
        out.append(f'    bounds: {{ w: {w}, h: {h} }},')
        out.append('    anims: {')
        for a in anims:
            out.append(f"      '{a['id']}': {{ next: '{a['next']}', loop: {str(a['loop']).lower()}, frames: [")
            for f in a['frames']:
                out.append(f"        {{ ms: {f['ms']}, x: {f['x']}, y: {f['y']}, w: {f['w']}, h: {f['h']}, "
                           f"dx: {f['dx']}, dy: {f['dy']}, flip: {str(f['flip']).lower()} }},")
            out.append('      ] },')
        out.append('    }')
        out.append('  },')
    out += ['};', '']
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out))
    print(f'[OK] {OUT}: {len(ANIMATORS)} animators')


if __name__ == '__main__':
    main()
