#!/usr/bin/env python3
"""
Converts the `.ani` animators used by the ported NPCs and enemies into TypeScript data:

  python scripts/export_animations.py

  - `_ref_repo/Data/Animations/NPCs/*.ani`  -> `src/data/npcAnimations.ts`   (sheet `/assets/ui/npcs.png`)
  - `_ref_repo/Data/Animations/<dir>/*.ani` -> `src/data/enemyAnimations.ts` (sheet `/assets/ui/enemies.png`)

.ani format (AnimatorSaveLoad.cs): version, sprite sheet, then one line per animation:
  id;next;loopCount;offsetX;offsetY;frameCount;{time;srcX;srcY;srcW;srcH;offX;offY;colX;colY;colW;colH;mirrorV;mirrorH}*
Each exported frame keeps the draw offset (animation offset + frame offset) relative to the sprite
origin. NPC `bounds` reproduces Animator.UpdateAnimationSize for the first animation (ObjPerson
centres its sprite with it); enemy frames keep their collision rectangle (Animator.GetCollisionBox),
used by weapon hitboxes such as the Moblin's sword.
"""

import os

ANI_ROOT = os.path.join('_ref_repo', 'Data', 'Animations')
NPC_OUT = os.path.join('src', 'data', 'npcAnimations.ts')
ENEMY_OUT = os.path.join('src', 'data', 'enemyAnimations.ts')

# Animators used by src/data/npcs.ts
NPC_ANIMATORS = ['npc04', 'npc07', 'npc09', 'npc_green_boy', 'shopkeeper', 'npc_trendy', 'npc_woman_broom',
                 'npc_fisherman', 'dog', 'bowWowSmall', 'BowWow', 'npc_boy_left', 'npc_boy_right',
                 'witch', 'raccoon', 'tarin']

# Animators used by src/data/enemies.ts: TS key -> .ani path under Data/Animations
ENEMY_ANIMATORS = {
    'moblin': 'Enemies/moblin',
    'moblin_sword': 'Enemies/moblin sword',
    'moblin_sword_sword': 'Enemies/moblin sword sword',
    'spear': 'Objects/spear',
    'red_zol': 'Enemies/red zol',
    'gel': 'Enemies/gel',
    'green_zol': 'Enemies/green zol',
    'keese': 'Enemies/keese',
    'buzzblob': 'Enemies/buzzblob',
}


def parse_ani(path, sheet):
    with open(path, encoding='utf-8-sig') as f:
        lines = [l.rstrip('\r\n') for l in f]
    if len(lines) < 2 or lines[1].strip() != sheet:
        raise SystemExit(f'{path}: expected the {sheet} sheet')
    anims = []
    for line in lines[2:]:
        p = line.split(';')
        if len(p) < 16:
            continue
        anim_id, nxt, loops, aox, aoy, count = p[0].lower(), p[1].lower(), int(p[2]), int(p[3]), int(p[4]), int(p[5])
        frames = []
        for i in range(count):
            f = p[6 + i * 13: 6 + (i + 1) * 13]
            ms, x, y, w, h, ox, oy, cx, cy, cw, ch = (int(v) for v in f[:11])
            flip_v, flip_h = f[11] == 'True', f[12] == 'True'
            col = None
            if cw > 0 and ch > 0:
                # Animator.GetCollisionBox: offsets + collision rect, mirrored inside the source rect
                col = (aox + ox + (w - cw - cx if flip_h else cx), aoy + oy + (h - ch - cy if flip_v else cy), cw, ch)
            frames.append({'ms': ms, 'x': x, 'y': y, 'w': w, 'h': h, 'ox': ox, 'oy': oy,
                           'dx': aox + ox, 'dy': aoy + oy, 'flip': flip_h, 'flipV': flip_v, 'col': col})
        anims.append({'id': anim_id, 'next': nxt, 'loop': loops < 0, 'repeat': max(0, loops), 'frames': frames})
    return anims


def bounds(anim):
    # Animator.UpdateAnimationSize: left/top/right/bottom start at 0 and grow with each frame
    left = min([0] + [f['ox'] for f in anim['frames']])
    top = min([0] + [f['oy'] for f in anim['frames']])
    right = max([0] + [f['ox'] + f['w'] for f in anim['frames']])
    bottom = max([0] + [f['oy'] + f['h'] for f in anim['frames']])
    return right - left, bottom - top


def frame_ts(f, extended):
    s = (f"{{ ms: {f['ms']}, x: {f['x']}, y: {f['y']}, w: {f['w']}, h: {f['h']}, "
         f"dx: {f['dx']}, dy: {f['dy']}, flip: {str(f['flip']).lower()}")
    if extended and f['flipV']:
        s += ', flipV: true'
    if extended and f['col']:
        cx, cy, cw, ch = f['col']
        s += f', col: {{ x: {cx}, y: {cy}, w: {cw}, h: {ch} }}'
    return s + ' },'


def anims_ts(anims, extended):
    out = ['    anims: {']
    for a in anims:
        repeat = f", repeat: {a['repeat']}" if extended and a['repeat'] else ''
        out.append(f"      '{a['id']}': {{ next: '{a['next']}', loop: {str(a['loop']).lower()}{repeat}, frames: [")
        out += [f'        {frame_ts(f, extended)}' for f in a['frames']]
        out.append('      ] },')
    out.append('    }')
    return out


def write(path, lines, count):
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print(f'[OK] {path}: {count} animators')


def export_npcs():
    out = [
        '// AUTO-GENERATED by scripts/export_animations.py from _ref_repo/Data/Animations/NPCs — do not edit by hand.',
        '// Generated data: exceeds the ~300 line guideline on purpose (one frame per line).',
        "import { AnimatorDef } from '../entities/AnimPlayer';",
        '',
        'export interface NpcAnimator extends AnimatorDef {',
        '  bounds: { w: number; h: number }; // size of the first animation (ObjPerson sprite centring)',
        '}',
        '',
        'export const NPC_ANIMATORS: Record<string, NpcAnimator> = {',
    ]
    for name in NPC_ANIMATORS:
        anims = parse_ani(os.path.join(ANI_ROOT, 'NPCs', f'{name}.ani'), 'npcs.png')
        w, h = bounds(anims[0])
        out.append(f'  {name}: {{')
        out.append(f"    first: '{anims[0]['id']}',")
        out.append(f'    bounds: {{ w: {w}, h: {h} }},')
        out += anims_ts(anims, extended=False)
        out.append('  },')
    out += ['};', '']
    write(NPC_OUT, out, len(NPC_ANIMATORS))


def export_enemies():
    out = [
        '// AUTO-GENERATED by scripts/export_animations.py from _ref_repo/Data/Animations — do not edit by hand.',
        '// Generated data: exceeds the ~300 line guideline on purpose (one frame per line).',
        '// Sheet: /assets/ui/enemies.png (copied from `_ref_repo/Data/Map Objects/enemies.png`).',
        "import { AnimatorDef } from '../entities/AnimPlayer';",
        '',
        'export const ENEMY_ANIMATORS: Record<string, AnimatorDef> = {',
    ]
    for key, rel in ENEMY_ANIMATORS.items():
        anims = parse_ani(os.path.join(ANI_ROOT, *rel.split('/')) + '.ani', 'enemies.png')
        out.append(f'  {key}: {{')
        out.append(f"    first: '{anims[0]['id']}',")
        out += anims_ts(anims, extended=True)
        out.append('  },')
    out += ['};', '']
    write(ENEMY_OUT, out, len(ENEMY_ANIMATORS))


if __name__ == '__main__':
    export_npcs()
    export_enemies()
